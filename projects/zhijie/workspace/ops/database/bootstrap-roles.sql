-- 仅在织界专用数据库中，由数据库管理员在首次迁移前执行。
-- 不设置密码；凭据和 LOGIN 由部署系统通过秘密渠道另行配置。
BEGIN;
CREATE ROLE zhijie_migrator NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE zhijie_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE zhijie_support NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO zhijie_migrator;
GRANT USAGE ON SCHEMA public TO zhijie_app;
GRANT USAGE ON SCHEMA public TO zhijie_support;
DO $$ BEGIN
    EXECUTE format('REVOKE CREATE, TEMPORARY ON DATABASE %I FROM PUBLIC', current_database());
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO zhijie_migrator, zhijie_app, zhijie_support', current_database());
END $$;
COMMIT;
