module.exports = async ({ evaluate, click, assert, delay, command, screenshot }) => {
  await command('Page.reload', { ignoreCache: true }); await delay(300);
  await command('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await evaluate('state.view="groupChat";state.groupId="expedition";render()');
  await click('review-scenarios');
  await evaluate('document.querySelector("[data-action=review-peer-mode][data-mode=offline]").click()');
  assert('未入房可查看群同步，无副本显示暂不可用', await evaluate('!state.joined&&document.querySelector(".sync-notice").innerText.includes("暂不可用")'));
  await evaluate('document.getElementById("group-message-input").value="仅本机消息";sendTextMessage("group")');
  assert('无接收端不冒充送达', await evaluate('currentGroup().messages.at(-1).delivery==="pending"&&document.querySelector(".message-receipt").innerText.includes("待同步")'));
  await click('sync-history');
  assert('无在线副本重试保留本机消息与待同步状态', await evaluate('currentGroup().messages.at(-1).delivery==="pending"&&state.toast.includes("暂不可用")'));
  await click('attach-media');
  await evaluate('(async()=>{const c=document.createElement("canvas");c.width=c.height=8;const b=await new Promise(r=>c.toBlob(r,"image/png"));await selectMediaFile(new File([b],"peer.png",{type:"image/png"}))})()');
  await click('confirm-media'); await delay(1100);
  assert('无对端附件仅本机保存而非已接收', await evaluate('currentGroup().messages.at(-1).media&&currentGroup().messages.at(-1).delivery==="pending"&&state.toast.includes("待同步")'));
  await click('review-scenarios');
  await evaluate('document.querySelector("[data-action=review-peer-mode][data-mode=partial]").click()');
  await click('sync-history');
  assert('部分成员可达不显示全员送达', await evaluate('currentGroup().messages.at(-1).delivery==="partial"&&document.querySelector(".group-chat-body").innerText.includes("部分送达")'));
  await evaluate('window.deletedPeerMessage=currentGroup().messages.at(-1).id;document.querySelector(`[data-action=delete-message][data-id="${window.deletedPeerMessage}"]`).click()');
  await click('confirm-delete-message');
  await click('review-scenarios');
  await evaluate('document.querySelector("[data-action=review-peer-mode][data-mode=online]").click()');
  await click('sync-history');
  assert('副本恢复可同步而删除内容不复活', await evaluate('currentGroup().messages.find(m=>m.id===window.deletedPeerMessage).deleted&&!currentGroup().messages.find(m=>m.id===window.deletedPeerMessage).media&&currentGroup().messages.find(m=>m.text==="仅本机消息").delivery==="received"'));
  await evaluate('enterRoom("weekend")');
  assert('语音首先等待隧道', await evaluate('state.voice==="waiting"&&state.network==="connecting"'));
  await delay(800);
  await click('review-scenarios');
  await evaluate('document.querySelector("[data-scenario=network-nat]").click()');
  assert('NAT 失败无服务器回退且语音等待', await evaluate('state.network==="failed"&&state.voice==="waiting"&&document.body.innerText.includes("不会转由服务器传输")'));
  await evaluate('state.roomTab="chat";render();document.getElementById("room-message-input").value="隧道失败草稿";sendTextMessage("room")');
  assert('隧道失败不能继续投递房间消息', await evaluate('!currentRoom().messages.some(m=>m.text==="隧道失败草稿")&&document.getElementById("room-message-input").value==="隧道失败草稿"'));
  await click('network-retry'); await delay(650);
  assert('重试隧道后自动恢复语音', await evaluate('state.network==="connected"&&state.voice==="connected"'));
  await click('review-scenarios');
  await evaluate('document.querySelector("[data-scenario=voice-device]").click()');
  assert('音频专属故障不停止虚拟网络', await evaluate('state.voice==="failed"&&state.network==="connected"'));
  await command('Emulation.setDeviceMetricsOverride', { width: 600, height: 800, deviceScaleFactor: 1, mobile: false });
  await evaluate('state.view="groupChat";state.peerMode="offline";state.toast="";renderToast();render()');
  assert('600px 副本提示与重试入口不横向溢出', await evaluate('document.documentElement.scrollWidth<=600&&document.querySelector("[data-action=sync-history]").getBoundingClientRect().width>0'));
  assert('滚动后副本提示未被群标题遮挡', await evaluate('document.querySelector(".sync-notice").getBoundingClientRect().top>=document.querySelector(".group-chat-head").getBoundingClientRect().bottom'));
  await screenshot('prototype-peer-600.png');
  await command('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await screenshot('prototype-peer-sync.png');
};
